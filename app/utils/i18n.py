def get_current_language() -> str:
    """Resolve the active UI language."""

    if not has_request_context():
        return "en"

    if "language" in session and session["language"] in SUPPORTED_LANGUAGES:
        return session["language"]

    if current_user.is_authenticated:
        preferred = getattr(current_user, "preferred_language", None)
        if preferred in SUPPORTED_LANGUAGES:
            return preferred

    language = request.accept_languages.best_match(SUPPORTED_LANGUAGES.keys())
    return language or "en"


def set_language(language_code: str) -> bool:
    """Persist a selected language in the session."""

    if language_code not in SUPPORTED_LANGUAGES:
        return False

    session["language"] = language_code
    return True


def translate(key: str, language_code: str | None = None, **kwargs) -> str:
    """Translate a UI key with English fallback."""

    lang = language_code or get_current_language()
    value = TRANSLATIONS.get(lang, {}).get(key, TRANSLATIONS["en"].get(key, key))
    return value.format(**kwargs) if kwargs else value
